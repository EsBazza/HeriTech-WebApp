export async function mockTranslateText({
  text,
  targetLanguage,
  sourceLanguage = 'en'
}: TranslationRequest): Promise<TranslationResponse> {
  const langMap = MOCK_TRANSLATIONS[targetLanguage];

  if (Array.isArray(text)) {
    const translations = text.map(t => {
      if (langMap && langMap[t]) return langMap[t];
      return getMockFallback(t, targetLanguage);
    });
    
    return {
      translations,
      success: true,
      detectedLanguage: sourceLanguage
    };
  }

  const translation = langMap && langMap[text] ? langMap[text] : getMockFallback(text, targetLanguage);
  
  return {
    translations: [translation],
    success: true,
    detectedLanguage: sourceLanguage
  };
}

export async function mockTranslateBatch({
  texts,
  targetLanguage,
  sourceLanguage = 'en'
}: BatchTranslationRequest): Promise<BatchTranslationResponse> {
  const translations: Record<string, string> = {};
  const langMap = MOCK_TRANSLATIONS[targetLanguage];
  
  Object.entries(texts).forEach(([key, value]) => {
    const valStr = typeof value === 'string' ? value : String(value);
    translations[key] = langMap && langMap[valStr] ? langMap[valStr] : getMockFallback(valStr, targetLanguage);
  });

  return {
    translations,
    success: true
  };
}

// Check if we should use mock translations (when Google API is not available)
export function shouldUseMockTranslation(): boolean {
  // Check if Google Cloud credentials are properly configured
  const hasApiKey = !!process.env.GOOGLE_TRANSLATE_API_KEY;
  const hasProjectId = !!process.env.GOOGLE_CLOUD_PROJECT_ID;

  // 'AIzaSy' IS the standard Google API key prefix — it is NOT a placeholder.
  // Only treat keys as placeholders if they contain generic placeholder strings.
  const key = process.env.GOOGLE_TRANSLATE_API_KEY || '';
  const isPlaceholderKey =
    key.includes('YOUR_') ||
    key.includes('PLACEHOLDER') ||
    key.includes('xxx') ||
    key.length < 20;

  return !hasApiKey || !hasProjectId || isPlaceholderKey;
}